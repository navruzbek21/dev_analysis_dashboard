CREATE TABLE IF NOT EXISTS dashboard_metadata (
    dataset_name VARCHAR(100) PRIMARY KEY,
    dataset_version VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    row_count BIGINT NULL,
    description VARCHAR(500) NULL
);

CREATE TABLE IF NOT EXISTS dim_area (
    area_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kod_ploshchadi VARCHAR(255) NOT NULL,
    ngdu VARCHAR(255) NOT NULL,
    mest VARCHAR(255) NULL,
    dataset_version VARCHAR(100) NOT NULL,
    valid_from TIMESTAMP NULL,
    valid_to TIMESTAMP NULL,
    is_current BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS monthly_metrics (
    date TIMESTAMP NULL,
    year INTEGER NULL,
    ngdu VARCHAR(255) NULL,
    mest VARCHAR(255) NULL,
    ploshad VARCHAR(255) NULL,
    well_uid VARCHAR(255) NULL,
    debit_neft DOUBLE PRECISION NULL,
    debit_liq DOUBLE PRECISION NULL,
    debit_vod DOUBLE PRECISION NULL,
    priem DOUBLE PRECISION NULL,
    wc DOUBLE PRECISION NULL,
    dataset_version VARCHAR(100) NOT NULL,
    loaded_at TIMESTAMP NOT NULL,
    source_file VARCHAR(500) NULL
);

